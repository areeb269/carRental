    public ArrayList<listOfPeople> personList()
    {
        ArrayList<listOfPeople> customerList=new ArrayList<>();
        Connection conn = null;
        Statement stmt = null;
        try
        {
            conn = getDatabaseCnnection();
            //STEP 4: Execute a query
            System.out.println("Creating statement...");
            stmt = conn.createStatement();
            String sql;
            sql = "SELECT * FROM customerinfo" ;
            ResultSet rs = stmt.executeQuery(sql);
            listOfPeople customers;
            while(rs.next())
            {
               customers = new listOfPeople(rs.getString("id"),rs.getString("name"),rs.getString("address")
              ,rs.getString("pnumber"),rs.getString("serialno"),rs.getString("rentdate"),rs.getString("returndate")
              ,rs.getString("rentdays"),rs.getString("additionaldays"),rs.getString("bill"));
  
            customerList.add(customers);
            }
            stmt.close();
            conn.close();
        }
        catch(Exception e)
        {
            JOptionPane.showMessageDialog(null,e);
        }
        return customerList;
    }

