    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        payment obj=new payment();
        car c =new car();
        String id =jTextField_ID.getText(); 
        String serialNo=jTextField_serialNo.getText();
        c.setYear2(jTextField_year.getText());
        c.setMonth2(jTextField_month.getText());
        c.setDate2(jTextField_date.getText());
        
        String returnDate= obj.dateReturn(c);
        c.setReturnDate(returnDate);
        
        c.setAddDays(jTextField_addDays.getText());
        c.setDamages(jTextField_damages.getText());
        
        String rent,days,add,damages;
        int r=0,ds=0,a=0,d=0,total=0;
        if((obj.enterReturnDate(id,c)==0)&&(obj.enterAdditionalDays(id,c)==0)&&(obj.enterDamages(id,c)==0))
        {
            rent= obj.searchRent(serialNo);
            //System.out.println("rent is "+rent);
            r=Integer.parseInt(rent);            
            days=obj.searchRentDays(id);
            //System.out.println("days is "+days);
            ds=Integer.parseInt(days);
            add=obj.searchAddDays(id);
            //System.out.println("add days is "+add);
            a=Integer.parseInt(add);
            ds=ds+a;  
            //System.out.println("total days "+ds);
            total = r*ds;
            
            //System.out.println("total bill (-damages) "+total);

            damages=c.getDamages();
            d=Integer.parseInt(damages);
            //System.out.println(d);
            if(d>0 && d<5)
            {
                total=total+2000;
            }
            else if(d>=5)
            {
                total=total+5000;
            }
            System.out.println("Total Bill is "+total);

            Integer i = new Integer(10);
            String totalBill = i.toString(total);
            //System.out.println("Value = " + totalBill);
            c.setBill(totalBill);
            if(obj.enterBill(id, c)==0)
            {
                JOptionPane.showMessageDialog(null,"Your Total bill is Rs." + total + " /-");
            }
            close();
            new customerMenu().setVisible(true);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

